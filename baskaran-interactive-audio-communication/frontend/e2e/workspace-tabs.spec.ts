test('S24-sized liquid glass dock keeps all five sections visible and content clear', async ({browser}) => {
  const context=await browser.newContext({viewport:{width:412,height:915},deviceScaleFactor:3.5,isMobile:true,hasTouch:true})
  const page=await context.newPage()
  await mockBackend(page)
  const filename='All About Dogs_ A Complete Guide.pdf'
  await page.route('**/api/v1/documents/',route=>route.fulfill({json:[{document_id:'doc-1',filename,file_type:'pdf',chunk_count:3}]}))
  await page.goto('/study-assistant')
  const dock=page.getByRole('navigation',{name:'Workspace navigation'})
  await expect(page.getByRole('tablist')).toBeVisible()
  await expect(page.locator('.vl-document-name')).toHaveText(filename)
  await expect(page.locator('.vl-document-name')).toBeInViewport()
  for (const name of ['Documents','Ask a question','Study tools','Saved library','History']) {
    const option=page.getByRole('tab',{name,exact:true})
    await expect(option).toBeInViewport({ratio:1})
    const box=await option.boundingBox()
    expect(box!.width).toBeGreaterThan(60)
    expect(box!.height).toBeGreaterThanOrEqual(62)
  }
  expect(await dock.evaluate(el=>getComputedStyle(el).backdropFilter)).toContain('blur')
  await page.screenshot({path:'.workspace-runtime/s24-glass-documents.png'})
  await selectWorkspace(page,'Study tools')
  await expect(page.locator('#tab-study-actions')).toHaveAttribute('aria-selected','true')
  await expect(page.getByText(/OpenClaw/)).toHaveCount(0)
  await page.evaluate(()=>window.scrollTo({top:document.documentElement.scrollHeight,behavior:'instant'}))
  await expect(dock).toBeInViewport({ratio:1})
  const lastButton=page.getByRole('button',{name:'Use audio revision command',exact:true})
  const dockBox=await dock.boundingBox()
  const buttonBox=await lastButton.boundingBox()
  expect(buttonBox!.y+buttonBox!.height).toBeLessThan(dockBox!.y)
  await selectWorkspace(page,'Saved library')
  await page.getByRole('button',{name:/Switch to dark mode/}).click()
  await page.screenshot({path:'.workspace-runtime/s24-glass-dark.png'})
  await page.emulateMedia({reducedMotion:'reduce'})
  await selectWorkspace(page,'History')
  expect(await dock.locator('[role=tablist]').evaluate(el=>getComputedStyle(el,'::before').transitionDuration)).toBe('1e-05s')
  await page.setViewportSize({width:915,height:412})
  await expect(dock).toBeInViewport({ratio:1})
  await selectWorkspace(page,'Saved library')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.close()
})
